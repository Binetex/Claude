/**
 * Разовый пересчёт итогов дней основного флориста за весь период с даты запуска расчёта.
 *
 * ЗАЧЕМ. Обычно пересчёт происходит сам, на изменениях (см. modules/finance/orderDayHook.ts):
 * заказ доставлен, подтверждён магазином, статус или дата правлены руками, переназначен
 * флорист, поправлены входные данные. Интервального пересчёта в воркере нет намеренно — он
 * гонял все дни подряд каждые 15 минут, и работа росла с каждым прожитым днём.
 *
 * Но есть случай, который никаким изменением заказа не выражается: поменялся ПРОЦЕНТ доли,
 * налоговая политика или дата старта расчёта. Тогда пересчитать нужно всю историю сразу —
 * для этого и нужен этот скрипт.
 *
 * Денег он не двигает: переписывается итог дня, из которого долг только выводится. Реальная
 * выплата — всегда ручная операция владельца, поэтому запускать безопасно.
 *
 *   npm run finance:recompute
 */
import { prisma } from "../src/lib/db";
import { dispatchPrimaryShare } from "../src/modules/finance/shareDispatcher";

async function main() {
  const r = await dispatchPrimaryShare(prisma);
  if (r.reason) {
    console.log(`Пересчёт не выполнен: ${r.reason}`);
    return;
  }
  console.log(`Дней пересчитано: ${r.days}`);
  console.log(`  посчитаны целиком (дают заработок): ${r.complete}`);
  console.log(`  не хватает данных: ${r.incomplete}`);
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
