-- Инструкция курьеру — отдельное поле заказа.
--
-- До этого в Burq как dropoff-инструкция уезжала customerNote, а ею команда пользуется как
-- ВНУТРЕННЕЙ заметкой: из 11 заполненных заказов 10 заведены руками («Просит пораньше»,
-- «Записку именно на 3 коробки», «Тест»). Всё это молча читал курьер. Теперь заметка
-- остаётся внутренней, а курьеру уходит только то, что для него и написали.
--
-- Данные НЕ переносим: заказы с прежними заметками давно доставлены, а копировать внутренние
-- записи в поле, видимое курьеру, — ровно та ошибка, которую эта миграция исправляет.
ALTER TABLE "Order" ADD COLUMN "courierNote" TEXT NOT NULL DEFAULT '';
