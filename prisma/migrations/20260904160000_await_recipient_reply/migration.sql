-- «Ждём ответ получателя» — теперь свойство КОНКРЕТНОГО правила, а не типа события.
--
-- До этого эскалацию запускало любое SMS получателю по событию «Доставка сегодня». Правило
-- такое одно (вопрос про готовность принять букет при указанной квартире), но второе на то же
-- событие цепляло бы цепочку к своему сообщению — в том числе к тексту, который вопросом не
-- является, а значит и ждать по нему ответа незачем.
ALTER TABLE "Automation" ADD COLUMN "awaitRecipientReply" BOOLEAN NOT NULL DEFAULT false;

-- Сохраняем текущее поведение: у правил, которые эскалацию запускают СЕЙЧАС, флаг включён.
-- Без этого шага деплой тихо выключил бы уже работающую цепочку.
--
-- Условие повторяет прежнее ровно: цепочку заводила отправка SMS получателю по «Доставке
-- сегодня», а получателю уходит и правило с адресатом BOTH — поэтому оно тоже здесь.
-- smsEnabled — потому что без SMS отправки не было, и флаг был бы мёртвым; тот же инвариант
-- держит awaitReplyAllowed() при сохранении правила.
UPDATE "Automation"
SET "awaitRecipientReply" = true
WHERE "triggerType" = 'DELIVERY_TODAY'
  AND "audience" IN ('RECIPIENT', 'BOTH')
  AND "smsEnabled" = true
  AND "deletedAt" IS NULL;
