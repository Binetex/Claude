-- Точка описывается СВОИМ индексом, а не списком обслуживаемых: какие адреса к ней относятся,
-- система считает по расстоянию. Перечислять районы руками бессмысленно — их десятки, и
-- ошибка в списке молча уводит заказ просить отзыв не в тот магазин.
ALTER TABLE "GoogleLocation" ADD COLUMN "zipCode" TEXT;

-- Переносим первый код из прежнего списка: справочник только что заведён, но терять введённое
-- нельзя даже в этом случае.
UPDATE "GoogleLocation"
SET "zipCode" = substring("zips"[1] from '^[0-9]{5}')
WHERE array_length("zips", 1) >= 1;

ALTER TABLE "GoogleLocation" DROP COLUMN "zips";
