/**
 * Ошибка Burq человеческими словами.
 *
 * Раньше любой сбой превращался в «Ошибка обращения к Burq. Попробуйте позже.» — фразу, которая
 * не различает «у магазина не заданы ключи», «вы ввели несуществующий номер заказа» и «у Burq
 * упал сервер». Первое чинится за минуту в настройках, второе — исправлением опечатки, третье
 * не чинится вовсе, и ждать имеет смысл только в третьем случае.
 *
 * Показываем причину, но не внутренности: статус и код Burq — это адрес проблемы, а не секрет.
 */
import { BurqApiError } from "./client";

export function burqErrorMessage(err: unknown): string {
  if (err instanceof BurqApiError) {
    if (err.status === 401 || err.status === 403) {
      return "Burq отклонил доступ — проверьте ключи Burq в настройках магазина.";
    }
    if (err.status === 404) {
      return "Burq не знает такого заказа — проверьте Burq Order ID.";
    }
    if (err.status === 429) {
      return "Burq просит подождать: слишком много запросов подряд. Повторите через минуту.";
    }
    if (err.status >= 500) {
      return "У Burq сбой на их стороне — попробуйте позже, с нашей стороны всё в порядке.";
    }
    // 4xx с кодом: сам код Burq говорит больше, чем любая наша формулировка.
    const detail = err.code ? ` (${err.code})` : "";
    return `Burq отклонил запрос${detail}: ${err.message}`;
  }

  // Не ответил вовсе: сеть, таймаут, DNS. Отличать это от отказа важно — при обрыве запрос мог
  // и дойти, поэтому «попробуйте позже» здесь честнее, чем на явном отказе.
  const text = err instanceof Error ? err.message : String(err);
  if (/timeout|ETIMEDOUT|ECONNRESET|ENOTFOUND|fetch failed|network/i.test(text)) {
    return "Burq не ответил (сеть или таймаут). Попробуйте ещё раз через минуту.";
  }

  if (/not configured|нет ключей|credentials/i.test(text)) {
    return "Burq не настроен у этого магазина — заполните ключи в настройках.";
  }

  return "Не удалось обратиться к Burq. Подробности — в системных событиях.";
}
