/**
 * Приведение текста открытки к тому виду, в котором его написал клиент. Чистые функции,
 * без сети и БД. Две правки, обе про мусор от магазина, а не про смысл:
 *
 *   1) служебный хвост приложения доставки;
 *   2) HTML-сущности («&amp;» вместо «&»).
 *
 * Обе намеренно узкие: испортить поздравление хуже, чем оставить лишнее.
 */

// ─── 1. Хвост приложения доставки ──────────────────────────────────────────────────────
//
// Приложения доставки дописывают дату и окно прямо в конец записки:
//
//   С днём рождения! | Delivery Date: Wed Aug 5 2026 | Delivery Time: 11:30 AM - 5:00 PM
//
// К поздравлению это отношения не имеет: и дату, и окно мы читаем ОТДЕЛЬНО — из атрибутов
// заказа (`noteAttr` в shopify/orderAdapter, mapping meta-полей у Woo). То есть хвост —
// чистое дублирование, и вырезав его, мы ничего не теряем.

/** Ключи, которые пишет не человек, а приложение магазина. Регистр не важен. */
const TAIL_KEYS = ["delivery date", "delivery time", "delivery window"];

/** Один хвостовой фрагмент вида `| Ключ: значение` в самом конце строки. */
const TAIL_SEGMENT = /\s*\|\s*([^|:]+?)\s*:\s*[^|]*$/;

/**
 * Тот же фрагмент, но БЕЗ ведущей черты и занимающий строку целиком. Когда клиент не написал
 * поздравления, приложение пишет хвост с самого начала: «Delivery Date: … | Delivery Time: …»,
 * и у первого фрагмента черты перед ним нет.
 */
const WHOLE_SEGMENT = /^\s*([^|:]+?)\s*:\s*[^|]*$/;

const isTailKey = (key: string) => TAIL_KEYS.includes(key.trim().toLowerCase());

/**
 * Убирает с конца записки все служебные фрагменты подряд. Останавливается на первом же
 * фрагменте с незнакомым ключом — дальше начинается текст клиента.
 *
 * Режем ТОЛЬКО с конца: такой же фрагмент в середине остаётся на месте, там это могут быть
 * слова клиента. Записка, состоявшая из одного хвоста, становится пустой.
 */
export function stripDeliveryTail(note: string): string {
  let out = note;
  for (;;) {
    const m = TAIL_SEGMENT.exec(out);
    if (!m || !isTailKey(m[1])) break;
    out = out.slice(0, m.index);
  }
  // Не осталось ли служебным и то, что было перед первой чертой.
  const whole = WHOLE_SEGMENT.exec(out);
  if (whole && isTailKey(whole[1])) return "";
  return out.trimEnd();
}

// ─── 2. HTML-сущности ──────────────────────────────────────────────────────────────────
//
// Магазин отдаёт записку в HTML-экранированном виде, и «Nick & Laurel» приезжает как
// «Nick &amp; Laurel». На карточке и в SMS это печатается буквально.

/**
 * Только именованные сущности, которые реально встречаются в поздравлениях. Произвольные
 * числовые НЕ раскрываем: из них получаются управляющие символы, а пользы никакой.
 *
 * `&amp;` идёт ПОСЛЕДНИМ и обрабатывается отдельно — иначе «&amp;lt;» раскрылось бы дважды
 * и превратилось в «<».
 */
const ENTITIES: Record<string, string> = {
  "&lt;": "<",
  "&gt;": ">",
  "&quot;": '"',
  "&#34;": '"',
  "&#039;": "'",
  "&#39;": "'",
  "&apos;": "'",
  "&nbsp;": " ",
  "&hellip;": "…",
  "&mdash;": "—",
  "&ndash;": "–",
  "&lsquo;": "‘",
  "&rsquo;": "’",
  "&ldquo;": "“",
  "&rdquo;": "”",
};

const ENTITY_RE = new RegExp(Object.keys(ENTITIES).join("|"), "g");

/** Раскрывает HTML-сущности в тексте открытки. */
export function decodeHtmlEntities(note: string): string {
  return note.replace(ENTITY_RE, (e) => ENTITIES[e]).replace(/&amp;/g, "&");
}

/**
 * Полная очистка записки: сначала хвост, потом сущности.
 *
 * Порядок важен. Сущности раскрываются ПОСЛЕ среза, чтобы экранированная вертикальная черта
 * не превратилась в настоящую и не создала хвост там, где его не было.
 */
export function cleanCardMessage(note: string): string {
  return decodeHtmlEntities(stripDeliveryTail(note));
}
