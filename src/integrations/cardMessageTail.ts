/**
 * Срез служебного хвоста с текста открытки. Чистая функция, без сети и БД.
 *
 * Приложения доставки в магазинах дописывают дату и окно доставки прямо в конец записки:
 *
 *   С днём рождения! | Delivery Date: Wed Aug 5 2026 | Delivery Time: 11:30 AM - 5:00 PM
 *
 * К поздравлению это отношения не имеет: и дату, и окно мы читаем ОТДЕЛЬНО — из атрибутов
 * заказа (`noteAttr` в shopify/orderAdapter, mapping meta-полей у Woo). То есть хвост —
 * чистое дублирование, и вырезав его, мы ничего не теряем.
 *
 * Правило намеренно узкое: режем ТОЛЬКО с конца и ТОЛЬКО по известным ключам. Такой же
 * фрагмент в середине остаётся на месте — там это могут быть слова клиента, а испортить
 * поздравление хуже, чем оставить лишнее.
 */

/** Ключи, которые пишет не человек, а приложение магазина. Регистр не важен. */
const TAIL_KEYS = ["delivery date", "delivery time", "delivery window"];

/** Один хвостовой фрагмент вида `| Ключ: значение` в самом конце строки. */
const TAIL_SEGMENT = /\s*\|\s*([^|:]+?)\s*:\s*[^|]*$/;

/**
 * Тот же фрагмент, но БЕЗ ведущей черты и занимающий строку целиком. Когда клиент не написал
 * поздравления, приложение пишет хвост с самого начала: «Delivery Date: … | Delivery Time: …»,
 * и у первого фрагмента черты перед ним нет.
 */
const WHOLE_SEGMENT = /^\s*([^|:]+?)\s*:\s*[^|]*$/;

const isTailKey = (key: string) => TAIL_KEYS.includes(key.trim().toLowerCase());

/**
 * Убирает с конца записки все служебные фрагменты подряд. Останавливается на первом же
 * фрагменте с незнакомым ключом — дальше начинается текст клиента.
 *
 * Записка, состоявшая из одного хвоста, становится пустой: слов клиента в ней и не было.
 */
export function stripDeliveryTail(note: string): string {
  let out = note;
  for (;;) {
    const m = TAIL_SEGMENT.exec(out);
    if (!m || !isTailKey(m[1])) break;
    out = out.slice(0, m.index);
  }
  // Не осталось ли служебным и то, что было перед первой чертой.
  const whole = WHOLE_SEGMENT.exec(out);
  if (whole && isTailKey(whole[1])) return "";
  return out.trimEnd();
}
