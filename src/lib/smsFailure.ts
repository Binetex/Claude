/**
 * Почему SMS не ушла — человеческим языком.
 *
 * Один текст на все экраны: карточка заказа, Telegram-бот с черновиками ассистента. Раньше
 * подписи жили только в карточке, и в Telegram владелец видел голое `quo_client` — код, по
 * которому непонятно ни что случилось, ни что делать. Второму списку подписей появляться нельзя:
 * разъедется с этим в первый же месяц.
 *
 * Коды провайдера (QUO) для отправки сообщения, по их документации:
 *  400 `0206400` — номер не прошёл регистрацию A2P 10DLC;
 *  401 `0200401` — ключ не принят;
 *  402 `0201402` — нет средств на аккаунте (истёкшая подписка/пустой баланс);
 *  403 `0204403` — исчерпан дневной лимит A2P;
 *  404 `0200404` — ресурс не найден;
 *  5xx — сбой на их стороне.
 */

/** Подпись по HTTP-статусу провайдера: она точнее, чем класс ошибки. */
function byProviderStatus(status: number): string | null {
  if (status === 400) return "QUO не пропустил сообщение: номер магазина не прошёл регистрацию A2P (проверьте статус регистрации в кабинете QUO).";
  if (status === 401) return "QUO не принял ключ доступа — сообщение не ушло.";
  if (status === 402) return "QUO: на аккаунте закончились деньги — сообщение не ушло. Пополните баланс QUO: пока он пуст, клиентам не уходит ни одна SMS.";
  if (status === 403) return "QUO: исчерпан дневной лимит сообщений A2P. Отправка возможна завтра или после увеличения лимита.";
  if (status === 404) return "QUO не нашёл номер отправителя — проверьте настройки магазина.";
  if (status === 429) return "QUO: слишком много запросов, попробуйте через минуту.";
  if (status >= 500) return "QUO временно недоступен — попробуйте позже.";
  return null;
}

const CODES: Record<string, string> = {
  empty_text: "Пустой текст.",
  too_long: "Сообщение слишком длинное.",
  invalid_target_phone: "Номер получателя не распознан.",
  store_no_quo_number: "У магазина не задан номер отправителя QUO.",
  from_number_not_owned: "Этот QUO-номер не принадлежит магазину — отправка с него запрещена.",
  store_quo_disabled: "SMS через QUO у этого магазина выключены.",
  quo_not_configured: "Интеграция QUO не настроена.",
  order_not_found: "Заказ не найден.",
  missing_idempotency_key: "Повторите отправку.",
  previous_attempt_failed: "Прошлая попытка не удалась и сообщение не ушло. Нажмите «Отправить» ещё раз.",
  quo_auth: "QUO отклонил запрос (авторизация).",
  quo_forbidden: "QUO: недостаточно прав.",
  quo_not_found: "QUO: ресурс не найден.",
  quo_rate_limit: "QUO: превышен лимит запросов, попробуйте позже.",
  quo_server: "QUO временно недоступен, попробуйте позже.",
  quo_network: "Сетевая ошибка при обращении к Quo.",
  quo_client: "QUO отклонил запрос.",
};

/**
 * `detail` — «402» или «402:0201402» из ответа провайдера. Сам код показываем в конце: с ним
 * поддержка QUO отвечает по существу, а без него разговор начинается с «пришлите скриншот».
 */
export function describeSendFailure(code: string, detail?: string | null): string {
  const status = Number((detail ?? "").split(":")[0]);
  const byStatus = Number.isFinite(status) && status > 0 ? byProviderStatus(status) : null;
  const base = byStatus ?? CODES[code] ?? code;
  return detail && byStatus ? `${base} (код ${detail})` : base;
}
