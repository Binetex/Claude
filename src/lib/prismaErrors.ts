/**
 * Распознавание ошибок Prisma по коду. Одна реализация на проект: копий было семь (каналы, движки цепочек, QUO-приём и backfill,
 * телеграм), и
 * проверка «нарушен ли уникальный индекс» — ровно то, что обязано совпадать везде, где на ней
 * держится идемпотентность.
 */
export function isP2002(err: unknown): boolean {
  return !!err && typeof err === "object" && "code" in err && (err as { code?: string }).code === "P2002";
}
