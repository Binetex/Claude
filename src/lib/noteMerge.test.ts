import { describe, it, expect } from "vitest";
import { mergeNoteEdit } from "./noteMerge";

/**
 * Человек правит заметку, а система тем временем дописывает строку сверху (ИИ, доплата, перенос).
 * Сохранение правки не должно эту строку затереть (владелец 09.10.2026).
 */
describe("mergeNoteEdit", () => {
  const base = "Позвонить за 30 минут";

  it("за время правки ничего не дописали — сохраняется правка как есть", () => {
    expect(mergeNoteEdit(base, base, "Позвонить за час")).toBe("Позвонить за час");
  });

  it("ИИ дописал строку сверху — она остаётся над правкой человека", () => {
    const ai = `07.10, 13:32 · Клиент (SMS): готов принять before 5pm\n———\n${base}`;
    expect(mergeNoteEdit(ai, base, "Позвонить за час")).toBe("07.10, 13:32 · Клиент (SMS): готов принять before 5pm\n———\nПозвонить за час");
  });

  it("доплата или перенос дописали строку без разделителя — тоже сохраняется", () => {
    expect(mergeNoteEdit(`Доплата: другой букет\n${base}`, base, "Код 1408")).toBe("Доплата: другой букет\nКод 1408");
  });

  it("заметки не было, система завела её — правка встаёт под строкой системы", () => {
    expect(mergeNoteEdit("ИИ перенёс доставку на 10/9", "", "Код 1408")).toBe("ИИ перенёс доставку на 10/9\nКод 1408");
  });

  it("человек стёр заметку, а сверху дописали — остаётся только дописанное, без висящего разделителя", () => {
    expect(mergeNoteEdit(`07.10 · готов после 5\n———\n${base}`, base, "")).toBe("07.10 · готов после 5");
  });

  it("кто-то переписал середину — сохраняется правка человека, без конфликтов", () => {
    expect(mergeNoteEdit("Совсем другой текст", base, "Позвонить за час")).toBe("Позвонить за час");
  });
});
