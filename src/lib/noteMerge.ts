/**
 * Заметка заказа, которую человек правил, пока система дописывала в неё строки.
 *
 * Система пишет в заметку только СВЕРХУ: ИИ — «клиент готов принять после 5», доплата, замена
 * букета, перенос доставки. Человек открыл заметку, правит, а сверху тем временем появилась строка —
 * сохранение целиком затёрло бы её (владелец 09.10.2026; до этого спасала проверка «заказ изменён
 * другим пользователем», которую сняли за ложные срабатывания). Поэтому форма присылает и правку, и
 * заметку, какой она была в начале правки: дописанное сверху с тех пор сохраняется над правкой.
 *
 * Изменилось не сверху (кто-то переписал середину) — сохраняется правка человека, как раньше:
 * всплывающих конфликтов больше нет, кто что менял — в аудите.
 */
export function mergeNoteEdit(current: string, base: string, edited: string): string {
  if (current === base) return edited;
  if (!base.trim()) {
    // Заметки не было, система завела её первой строкой.
    return edited.trim() ? `${current}\n${edited}` : current;
  }
  if (!current.endsWith(base)) return edited;
  // Дописанное сверху вместе с переводом строки (или разделителем) перед прежним текстом.
  const added = current.slice(0, current.length - base.length);
  return edited.trim() ? `${added}${edited}` : added.replace(/\s*(?:———\s*)?$/, "");
}
