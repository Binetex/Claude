/**
 * Как секреты выглядят в интерфейсе.
 *
 * Владелец обязан видеть, КАКОЙ ключ сейчас лежит: ключи перевыпускают, и «настроен» ничего не
 * отвечает на вопрос «тот ли это ключ, что я только что выпустил». Показываем хвост — последние
 * четыре знака, по ним значение узнаётся и не раскрывается.
 *
 * Фразы «пусто = не менять» в полях нет намеренно (решение владельца 07.09.2026): пустое поле и
 * так ничего не меняет, а место подсказки дороже занять настоящим хвостом.
 */

/** Хвост сохранённого секрета: «••••abcd». null — значения нет или маска слишком короткая. */
export function secretTail(mask: string | null | undefined): string | null {
  const t = (mask ?? "").replace(/[*•\s]/g, "");
  return t ? `••••${t.slice(-4)}` : null;
}

/** Подсказка поля ввода: название плюс хвост того, что лежит сейчас. */
export function secretPlaceholder(mask: string | null | undefined, fieldName: string): string {
  const tail = secretTail(mask);
  return tail ? `${fieldName} · сейчас ${tail}` : fieldName;
}
