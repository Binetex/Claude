import { requireRole } from "@/lib/rbac";
import { AutomationsTabs } from "./AutomationsTabs";

/**
 * Общая обвязка раздела «Автоматизации»: вкладки на каждой странице.
 *
 * Layout, а не копия в каждой странице, — раньше вкладки вставлялись руками в шесть
 * файлов, и на двух экранах (создание правила, карточка правила) их просто забыли:
 * человек проваливался в форму и терял раздел.
 *
 * Это ЕДИНСТВЕННАЯ проверка прав для страниц раздела — своей они не имеют, защита идёт от
 * группы (owner) и отсюда. Выносить любую страницу из-под этого layout нельзя, не добавив
 * requireRole в неё саму.
 */
export default async function AutomationsLayout({ children }: { children: React.ReactNode }) {
  await requireRole("OWNER");

  return (
    // Вкладки и содержимое — в ОДНОЙ колонке: иначе полоса вкладок шла бы во всю ширину
    // main, а список или форма под ней — по центру более узкой колонки. Собственную ширину
    // страницы раздела больше не задают, формы сужаются уже внутри своих карточек.
    <div className="mx-auto max-w-6xl space-y-4">
      <AutomationsTabs />
      {children}
    </div>
  );
}
