/**
 * Индекс каталога по внешнему id — общий для приёма заказов Shopify и WooCommerce.
 *
 * ЗАЧЕМ ОН ЕСТЬ. Один внешний id может встретиться в каталоге ДВАЖДЫ: вариация живёт
 * вариантом своего товара, но иногда та же вариация приезжает ещё и отдельным товаром
 * (вебхуком магазина или прогоном синхронизации), а позже помечается удалённой. Обе
 * записи откликаются на один id.
 *
 * Раньше карта строилась простым `new Map(rows.map(...))`, где побеждала последняя строка
 * выборки — то есть СЛУЧАЙНАЯ, порядок ничем не задан. Из-за этого заказ мог связаться с
 * удалённой записью, у которой нет ни состава, ни цены флориста. Дальше срабатывал фолбэк
 * «цены нет → берём цену клиента», и второстепенный флорист видел в позиции полную сумму
 * заказа (JF-1000970: $239 вместо $167).
 *
 * ПРАВИЛО. Живая запись всегда важнее удалённой; среди равных — синхронизированная свежее.
 *
 * Удалённые НЕ выбрасываются совсем, и это осознанно: если живой записи нет вовсе (товар
 * действительно убрали из магазина), связать заказ со старой лучше, чем не связать ни с
 * чем. Без связи позиция теряет состав букета и цену флориста — то есть ровно ту же
 * проблему, только гарантированно.
 */

export type CatalogRow = {
  externalId: string;
  remoteDeleted: boolean;
  lastSyncedAt: Date | null;
};

/** Строго ли `a` предпочтительнее `b`. */
function better(a: CatalogRow, b: CatalogRow): boolean {
  if (a.remoteDeleted !== b.remoteDeleted) return !a.remoteDeleted;
  return (a.lastSyncedAt?.getTime() ?? 0) > (b.lastSyncedAt?.getTime() ?? 0);
}

/** Карта «внешний id → лучшая запись». Порядок строк на результат не влияет. */
export function indexByExternalId<T extends CatalogRow>(rows: T[]): Map<string, T> {
  const byExt = new Map<string, T>();
  for (const row of rows) {
    const kept = byExt.get(row.externalId);
    if (!kept || better(row, kept)) byExt.set(row.externalId, row);
  }
  return byExt;
}
