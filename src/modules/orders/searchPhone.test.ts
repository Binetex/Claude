import { describe, it, expect } from "vitest";
import { searchPhoneDigits } from "./queries";

/**
 * 21.09.2026: владелец искал заказ по «(310) 904-8385» и не находил. Телефоны лежат в базе
 * десятком видов сразу (замер на проде: «9999999999» 556 раз, «+99999999999» 393, «(999)
 * 999-9999» 40, «999-999-9999» 38, и даже с неразрывным дефисом), а поиск сравнивал сырую
 * подстроку. Здесь зафиксирован разбор ЗАПРОСА; сравнение с колонкой чистит её тем же
 * regexp_replace на стороне Postgres.
 */
describe("телефон в поисковой строке", () => {
  it("любой вид записи сводится к одним и тем же цифрам", () => {
    for (const q of ["(310) 904-8385", "310-904-8385", "3109048385", "+1 (310) 904-8385", "+13109048385", "1 310 904 8385", "310.904.8385"]) {
      expect(searchPhoneDigits(q)).toBe("3109048385");
    }
  });

  it("неразрывный дефис из скопированного номера не мешает", () => {
    expect(searchPhoneDigits("+1 (310) 904‑8385")).toBe("3109048385");
  });

  it("короткие числа телефоном не считаются: иначе «#20211» и «2026» тащили бы случайные заказы", () => {
    for (const q of ["20211", "#20211", "2026", "904-8385".slice(0, 6), ""]) {
      expect(searchPhoneDigits(q)).toBe("");
    }
  });

  it("семизначный местный номер ищется, ведущая единица у одиннадцатизначного отбрасывается", () => {
    expect(searchPhoneDigits("904-8385")).toBe("9048385");
    expect(searchPhoneDigits("13109048385")).toBe("3109048385");
    // Двенадцать цифр — не американский номер, трогать его нельзя.
    expect(searchPhoneDigits("+44 20 7946 0958")).toBe("442079460958");
  });

  it("имя и адрес телефоном не становятся", () => {
    expect(searchPhoneDigits("Maddy Shell")).toBe("");
    expect(searchPhoneDigits("1244 N Orange Dr")).toBe("");
  });
});
