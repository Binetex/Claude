import "server-only";
/**
 * Сообщения, на которые ассистент не тратит ни ответа, ни запроса к модели.
 *
 * Рассылки про кредиты («Hi Emanouel, I can fund up to $2M») приходят на номера магазинов
 * десятками в неделю — и 05.09.2026 на одну такую клиенту магазина Par ушёл живой ответ
 * «Could you tell me the name on the order». Решать это правилом, а не моделью, дешевле.
 *
 * Но правило здесь решает МОЛЧАТЬ, и цена ошибки несимметрична: непойманную рассылку разберёт
 * модель и промолчит по своему правилу, а проглоченный живой клиент — это потерянный заказ.
 * Поэтому два ограничения:
 *
 *  1. Переписка, ПРИВЯЗАННАЯ К ЗАКАЗУ, не отсеивается никогда. Рассылка по определению приходит
 *     с чужого номера и к заказу не привязана, а вот «The gate code is 4455» — самый обычный
 *     текст клиента, и молчание на него срывает доставку.
 *  2. Категории берём те же, что на экране «Других сообщений» (вторая копия правил не нужна),
 *     но только SPAM и SERVICE: там ответ бессмыслен всегда. «Ищут работу» и всё остальное
 *     по-прежнему решает модель — на том конце человек.
 */
import { classifyThread } from "@/integrations/quo/otherMessages";

/** Причина молчания для журнала или null, если сообщение живое. */
export function junkReason(text: string, hasOrder: boolean): "spam_rule" | "service_rule" | null {
  if (hasOrder) return null;
  if (!text.trim()) return null;
  const topic = classifyThread([text]);
  if (topic === "SPAM") return "spam_rule";
  if (topic === "SERVICE") return "service_rule";
  return null;
}
