import { describe, it, expect } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";

/**
 * Фолбэк цены флориста: НОЛЬ, а не цена клиента.
 *
 * Прежнее поведение стоило дорого. Если у товара не была задана цена флориста, снимок
 * подставлял полную цену КЛИЕНТА — и второстепенный флорист видел её строкой «вам».
 * Число выглядело как настоящая цена, отличить его от честной было нельзя ни на экране,
 * ни в расчёте, и владелец узнавал о проблеме от флориста (JF-1000970: $239 вместо $167).
 *
 * Ноль говорит на языке финансового модуля: нулевой итог означает «цена не задана», и
 * заказ уходит в «Требует заполнения».
 *
 * Проверяется чтением исходника, а не вызовом: `resolveUnitPrices` не экспортируется и
 * требует живой БД, а поведение здесь задаёт ровно одна строка. Тест сторожит именно её —
 * чтобы возврат к цене клиента не прошёл незамеченным.
 */
const source = readFileSync(join(process.cwd(), "src/modules/pricing/service.ts"), "utf8");

describe("фолбэк цены флориста", () => {
  it("не найденная цена даёт ZERO", () => {
    expect(source).toMatch(/unitById\.set\(item\.id,\s*unit\s*\?\?\s*ZERO\)/);
  });

  it("цена клиента в фолбэк больше не подставляется", () => {
    expect(source).not.toMatch(/unit\s*\?\?\s*item\.externalPrice/);
  });

  it("ZERO — это действительно ноль", () => {
    expect(source).toMatch(/const ZERO = new Prisma\.Decimal\(0\)/);
  });

  it("в описании приоритетов нет обещания полной стоимости", () => {
    // Комментарий и код разъезжались бы незаметно: следующий читатель поверит комментарию.
    expect(source).not.toMatch(/ПОЛНАЯ стоимость заказа/);
  });
});
